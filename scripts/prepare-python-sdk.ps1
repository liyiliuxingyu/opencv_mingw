#requires -Version 7.2
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$StateFile,
    [Parameter(Mandatory)][string]$WheelResultFile,
    [Parameter(Mandatory)][string]$PackageRoot
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$state = Get-Content -LiteralPath $StateFile -Raw | ConvertFrom-Json
$wheel = Get-Content -LiteralPath $WheelResultFile -Raw | ConvertFrom-Json
if (-not (Test-Path -LiteralPath $wheel.wheel_path -PathType Leaf)) { throw 'The built Python wheel is missing.' }
$PackageRoot = [IO.Path]::GetFullPath($PackageRoot)
$destination = Join-Path $PackageRoot 'python-wheel'
New-Item -ItemType Directory -Force -Path $destination | Out-Null
Copy-Item -LiteralPath $wheel.wheel_path -Destination $destination
$loaderRoot = Join-Path $state.install_root 'python/cv2'
if (-not (Test-Path -LiteralPath (Join-Path $loaderRoot '__init__.py'))) { throw 'The SDK Python loader is missing.' }
$binaryRelative = [IO.Path]::GetRelativePath($loaderRoot, $state.opencv_bin_dir).Replace('\', '/')
$binaryRelativeLiteral = $binaryRelative | ConvertTo-Json -Compress
# Reuse the wheel's relative loader, including pinned NVIDIA pip package discovery.
# Never retain the absolute CUDA/build paths generated by upstream CMake.
$archive = [IO.Compression.ZipFile]::OpenRead($wheel.wheel_path)
try {
    $entry = $archive.GetEntry('cv2/config.py')
    if (-not $entry) { throw 'The wheel has no relocatable cv2 loader configuration.' }
    $reader = [IO.StreamReader]::new($entry.Open())
    try { $loader = $reader.ReadToEnd() } finally { $reader.Dispose() }
    $needle = "os.path.join(LOADER_DIR, '.libs')"
    if (-not $loader.Contains($needle)) { throw 'Unexpected wheel loader configuration.' }
    $loader = $loader.Replace($needle, "os.path.normpath(os.path.join(LOADER_DIR, $binaryRelativeLiteral))")
    [IO.File]::WriteAllText((Join-Path $loaderRoot 'config.py'), $loader, [Text.UTF8Encoding]::new($false))
    $versionConfig = 'config-' + $wheel.python.major_minor + '.py'
    $versionEntry = $archive.GetEntry("cv2/$versionConfig")
    if (-not $versionEntry) { throw 'The wheel has no matching CPython loader configuration.' }
    [IO.Compression.ZipFileExtensions]::ExtractToFile($versionEntry, (Join-Path $loaderRoot $versionConfig), $true)
} finally { $archive.Dispose() }
if ($state.PSObject.Properties['python'] -and $state.python) {
    $state | Add-Member -NotePropertyName python_build -NotePropertyValue $state.python -Force
}
$state | Add-Member -NotePropertyName python_bindings -NotePropertyValue $true -Force
$state | Add-Member -NotePropertyName python -NotePropertyValue $wheel.python -Force
$state | Add-Member -NotePropertyName python_wheel_path -NotePropertyValue $wheel.wheel_path -Force
$state | Add-Member -NotePropertyName python_wheel_result -NotePropertyValue ([IO.Path]::GetFullPath($WheelResultFile)) -Force
$state | ConvertTo-Json -Depth 20 | Set-Content -LiteralPath $StateFile -Encoding utf8NoBOM
$minor = [string]$wheel.python.version
if ($minor -match '^(3\.\d+)(?:\.|$)') { $minor = $Matches[1] } else { throw 'Invalid Python version in wheel metadata.' }
$filename = [IO.Path]::GetFileName($wheel.wheel_path)
$command = @"
@echo off
setlocal
set "VENV=%LOCALAPPDATA%\OpenCV-SDK\python-envs\$($state.package_name)"
py -$minor -m venv "%VENV%"
if errorlevel 1 goto failed
"%VENV%\Scripts\python.exe" -m pip install --only-binary=:all: --no-cache-dir "%~dp0python-wheel\$filename"
if errorlevel 1 goto failed
"%VENV%\Scripts\python.exe" -c "import cv2; print('OpenCV:', cv2.__version__); print('Loaded from:', cv2.__file__)"
if errorlevel 1 goto failed
echo Python cv2 is installed in "%VENV%".
echo Run "%VENV%\Scripts\python.exe" or activate "%VENV%\Scripts\activate.bat".
exit /b 0
:failed
echo Install 64-bit CPython $minor and check your network connection, then retry.
exit /b 1
"@
[IO.File]::WriteAllText((Join-Path $PackageRoot 'install-python.cmd'), ($command -replace '\r?\n', "`r`n"), [Text.UTF8Encoding]::new($false))
Write-Host "Prepared $filename for CPython $minor. The installer helper creates an isolated virtual environment."
